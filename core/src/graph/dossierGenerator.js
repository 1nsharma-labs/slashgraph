export class DossierGenerator {
  static generateMarkdownDossier(scanResult, projectName = 'System Architecture') {
    const lines = [];

    lines.push(`# 🗺️ Architecture Dossier: ${projectName}`);
    lines.push(`> Auto-generated by SlashGraph (Powered by Urlmind & SLASH). Zero-token context index for AI agents.\n`);

    // High Level Metrics
    lines.push(`## 📊 Topology Summary`);
    lines.push(`- **Scanned Files:** ${scanResult.filesScanned}`);
    lines.push(`- **Total Code Lines:** ${scanResult.totalLines}`);
    lines.push(`- **Exposed Routes:** ${scanResult.routes.length}`);
    lines.push(`- **Data Models / Entities:** ${scanResult.models.length}`);
    lines.push(`- **Required Env Variables:** ${scanResult.envVars.length}\n`);

    // Routes Table
    if (scanResult.routes.length > 0) {
      lines.push(`## ⚡ API Surface & Endpoints`);
      lines.push(`| Method | Route Path | Defined In | Framework |`);
      lines.push(`| :--- | :--- | :--- | :--- |`);
      scanResult.routes.forEach(r => {
        lines.push(`| \`${r.method}\` | \`${r.path}\` | \`${r.file}\` | ${r.type} |`);
      });
      lines.push('');
    }

    // Database Models
    if (scanResult.models.length > 0) {
      lines.push(`## 🗄️ Database Schemas & Entities`);
      scanResult.models.forEach(m => {
        const fields = m.fields ? ` (Fields: ${m.fields.join(', ')})` : '';
        lines.push(`- **${m.name}** [${m.orm}] in \`${m.file}\`${fields}`);
      });
      lines.push('');
    }

    // Environment Variables
    if (scanResult.envVars.length > 0) {
      lines.push(`## 🔐 Environment Configuration`);
      lines.push(`The following environment variables are referenced in source code:`);
      lines.push('```bash');
      scanResult.envVars.forEach(v => {
        lines.push(`${v}=<value>`);
      });
      lines.push('```\n');
    }

    // Module Categories
    lines.push(`## 📦 Module Categorization`);
    const categories = {};
    scanResult.modules.forEach(m => {
      categories[m.type] = categories[m.type] || [];
      categories[m.type].push(m.path);
    });

    for (const [type, files] of Object.entries(categories)) {
      lines.push(`### ${type} (${files.length})`);
      lines.push(files.slice(0, 10).map(f => `- \`${f}\``).join('\n'));
      if (files.length > 10) lines.push(`- *... and ${files.length - 10} more files*`);
      lines.push('');
    }

    return lines.join('\n');
  }

  static generateGraphJson(scanResult) {
    const nodes = [];
    const links = [];
    const nodeMap = new Set();

    // Add Modules
    scanResult.modules.forEach(m => {
      nodes.push({
        id: m.path,
        name: m.path.split('/').pop(),
        group: m.type,
        lines: m.lines
      });
      nodeMap.add(m.path);
    });

    // Add Routes
    scanResult.routes.forEach(r => {
      const routeId = `route:${r.method}:${r.path}`;
      if (!nodeMap.has(routeId)) {
        nodes.push({
          id: routeId,
          name: `${r.method} ${r.path}`,
          group: 'Route',
          file: r.file
        });
        nodeMap.add(routeId);
      }
      links.push({
        source: routeId,
        target: r.file,
        type: 'HANDLER'
      });
    });

    // Add Models
    scanResult.models.forEach(m => {
      const modelId = `model:${m.name}`;
      if (!nodeMap.has(modelId)) {
        nodes.push({
          id: modelId,
          name: m.name,
          group: 'DatabaseModel',
          file: m.file
        });
        nodeMap.add(modelId);
      }
      links.push({
        source: modelId,
        target: m.file,
        type: 'SCHEMA'
      });
    });

    return { nodes, links };
  }
}
